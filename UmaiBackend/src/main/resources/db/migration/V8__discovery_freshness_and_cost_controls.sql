-- Counters survive process restarts and are shared by all application instances.
CREATE TABLE external_api_usage (
    provider varchar(32) NOT NULL,
    period_start date NOT NULL,
    requests integer NOT NULL DEFAULT 0 CHECK (requests >= 0),
    PRIMARY KEY (provider, period_start)
);

CREATE TABLE data_refresh_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    status varchar(16) NOT NULL CHECK (status IN ('RUNNING', 'SUCCEEDED', 'PARTIAL', 'FAILED')),
    imported integer NOT NULL DEFAULT 0,
    cells_completed integer NOT NULL DEFAULT 0,
    message varchar(500)
);

CREATE TABLE restaurant_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id bigint NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    type varchar(16) NOT NULL CHECK (type IN ('CLOSED', 'HOURS', 'DIET', 'OTHER')),
    description varchar(2000) NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'RESOLVED', 'DISMISSED')),
    created_at timestamptz NOT NULL DEFAULT now(),
    resolved_at timestamptz,
    resolved_by bigint REFERENCES users(id),
    resolution varchar(2000)
);
CREATE UNIQUE INDEX uq_pending_report ON restaurant_reports (restaurant_id, user_id) WHERE status = 'PENDING';
CREATE INDEX ix_reports_pending ON restaurant_reports (status, created_at);
